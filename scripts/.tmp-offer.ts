import { eq } from "drizzle-orm";
import { getDb } from "../src/db";
import { listings, profiles } from "../src/db/schema";
import { makeOffer } from "../src/server/trading";
const db = getDb();
const laura = (await db.select().from(profiles)).find((p) => p.displayName === "Laura")!;
const [l] = await db.select().from(listings).where(eq(listings.id, "f7d8e97f-1a9c-4dc9-9031-56885652f1bb"));
await makeOffer({ userId: laura.id, slug: "rumbo-a-egghead", listingId: l.id, cards: ["11"] });
console.log("offer made");
process.exit(0);
